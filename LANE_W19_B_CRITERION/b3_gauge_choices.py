def wilson_broadcast(car):
    """all four plaquette holonomies W_{2k,2k+1} perfectly correlated: a GHZ in the WILSON loops.
       branch A: every link z = 0 ;  branch B: z = 1 on links 1,3,5,7,9 -- so every W = -1."""
    L = car["L"]
    a = sym_basis_state(car, 0)
    b = sym_basis_state(car, sum(1 << i for i in range(1, L, 2)))
    return project_physical((a + b) / np.linalg.norm(a + b), car)

