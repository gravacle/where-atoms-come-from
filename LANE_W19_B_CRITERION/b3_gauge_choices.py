"""
b3 -- THE GAUGE PROBLEM.  THIS IS THE ACTUAL RESIDUE.

In a gauge theory the physical algebra does not factorise into system and environment, so "I(S:F)"
is not defined until a BOUNDARY ALGEBRA is chosen.  This file enumerates the choices on the carrier,
computes I(S:F) under EACH, and asks whether the answer depends on the choice.

THE CHOICES, each a subalgebra assigned to a link region R, listed from largest to smallest.
  C1 EXT   extended Hilbert space (Buividovich-Polikarpov; Donnelly).  A_R = the FULL matrix algebra
           on the links of R.  Gauge invariance is imposed on the STATE, never on the cut.
  C5 MAG   magnetic centre (Casini-Huerta-Rosabal).  The Gauss law is DROPPED at the boundary
           vertices of R, so boundary holonomies enter A_R.
  C3 FULL  the full gauge-invariant region algebra: every gauge-invariant Pauli SUPPORTED in R.
  C2 ELEC  electric centre: only the gauge-invariant electric operators X_l, l in R.  Abelian.
  C6 DRESS dressed / Wilson-line choice (Donnelly-Freidel): electric operators in R together with
           gauge-invariant holonomies closed through a FIXED reference link.

DIFF THE ARMS: every choice is one line -- a different GENERATOR LIST fed to the SAME
algebra-entropy function.  The generator lists are printed below so the diff is on the page.
C1's numbers are computed by the reduced-density-matrix route instead, which b0 test [3] verified
agrees with the algebra route to 1e-8 (the algebra route costs 4^k and is unusable at k = 8).

ISOLATION LEDGER
  held fixed : carrier, state, system region, fragment list, delta.
  moved      : THE ALGEBRA CHOICE, and nothing else.
  KNOWN COLLAPSES, recorded rather than hidden:  on theta_L every vertex is a boundary vertex of
  every proper region, so C5 MAG returns the SAME generator list as C1 EXT there -- those two arms
  are NOT independent on theta and are marked (=C1).  The wheel and fan carriers, which have
  interior vertices, are run precisely to break that degeneracy.
"""
import numpy as np, itertools
from lib_b import *

np.set_printoptions(precision=6, suppress=True)
DELTA = 0.1
REF = None      # dressing reference link, set per carrier


def gens_for(choice, car, R):
    if choice == "C1_EXT":   return gens_EXT(car, R)
    if choice == "C5_MAG":   return gens_MAG(car, R)
    if choice == "C3_FULL":  return gens_FULL(car, R)
    if choice == "C2_ELEC":  return gens_ELEC(car, R)
    if choice == "C6_DRESS": return gens_DRESS(car, R, REF)
    raise KeyError(choice)

ORDER = ["C1_EXT", "C5_MAG", "C3_FULL", "C2_ELEC", "C6_DRESS"]

def show_gens(car, R, tag):
    print(f"  generator lists for R = {R}   ({tag})")
    for ch in ORDER:
        g = gens_for(ch, car, R)
        pairs, cen = algebra_structure(g)
        print(f"     {ch:<9} {[sp_str(a, car['L']) for a in g]}"
              f"   -> algebra = 2^{len(cen)} blocks of M_2^{len(pairs)}")

def I_choice(psi, E, car, ch, S, F):
    if ch == "C1_EXT":
        return mi_ext(psi, car["L"], S, F)
    v, _ = mutual_information(E, gens_for(ch, car, S), gens_for(ch, car, F))
    return v

def H_choice(psi, E, car, ch, S):
    if ch == "C1_EXT":
        return vn_entropy(reduce_links(psi, car["L"], S))
    v, _ = algebra_entropy(E, gens_for(ch, car, S))
    return v


