def elec_ghz(car):
    L = car["L"]; popc = popc_table(1 << L)
    a = np.ones(1 << L, dtype=complex); b = ((-1.0) ** popc[np.arange(1 << L)]).astype(complex)
    return project_physical(a / np.linalg.norm(a) + b / np.linalg.norm(b), car)

