def sections_from_class_weights(pv, d=1, direction=None, rng=None):
    """
    Ready state: weight pv[class] spread uniformly over the vertices of that
    class; fibre direction `direction` (default (1..1)/sqrt(d)) at every vertex,
    or independent Haar-random directions if rng is given.
    """
    cls = k1_classes()
    counts = {}
    for c in cls:
        counts[c] = counts.get(c, 0) + 1
    out = []
    for c in cls:
        if rng is not None:
            v = rng.normal(size=d) + 1j * rng.normal(size=d)
            v = v / np.linalg.norm(v)
        elif direction is not None:
            v = np.asarray(direction, dtype=complex); v = v / np.linalg.norm(v)
        else:
            v = np.ones(d, dtype=complex) / math.sqrt(d)
        out.append(math.sqrt(pv.get(c, 0.0) / counts[c]) * v)
    n = math.sqrt(sum(float(np.vdot(x, x).real) for x in out))
    return [x / n for x in out]
