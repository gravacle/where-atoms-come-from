# ------------------------------------------------------------- SU(2) helpers

PX = np.array([[0, 1], [1, 0]], dtype=complex)
PY = np.array([[0, -1j], [1j, 0]], dtype=complex)
PZ = np.array([[1, 0], [0, -1]], dtype=complex)

def su2(axis, theta):
    """exp(i theta n.sigma).  Eigenvalues exp(+- i theta)."""
    n = np.asarray(axis, dtype=float); n = n / np.linalg.norm(n)
    N = n[0] * PX + n[1] * PY + n[2] * PZ
    return math.cos(theta) * np.eye(2, dtype=complex) + 1j * math.sin(theta) * N

# ------------------------------------------- one-parameter subgroups as (V,w)

class OneParam:
    """A(x) = V diag(exp(i w x)) V^{-1}.  `w` INTEGER weights (primitive)."""
    def __init__(self, V, w):
        self.V = np.asarray(V, dtype=complex)
        self.w = np.asarray(w, dtype=int)
        self.Vi = np.linalg.inv(self.V)
        self.d = self.V.shape[0]
    def at(self, x):
        return self.V @ np.diag(np.exp(1j * self.w * x)) @ self.Vi

def op_u1(weights, sign=+1):
    """U(1) structure group, fibre C^d diagonal with integer weights."""
    w = sign * np.asarray(weights, dtype=int)
    return OneParam(np.eye(len(w), dtype=complex), w)

def op_su2(axis, sign=+1):
    """SU(2) fundamental, one-parameter subgroup with the given axis."""
    n = np.asarray(axis, dtype=float); n = n / np.linalg.norm(n)
    N = n[0] * PX + n[1] * PY + n[2] * PZ
    ev, V = np.linalg.eigh(N)          # eigenvalues +-1
    order = np.argsort(-ev)            # (+1, -1)
    V = V[:, order]
    w = sign * np.array([1, -1], dtype=int)
    return OneParam(V, w)

# --------------------------------------------- EXACT character decomposition

def modes(classes, sections, A: OneParam, B: OneParam, tol=1e-12):
    """
    Exact Fourier modes of z(x,y) = SUM_v <s_v, A(x)^{a_v} B(y)^{b_v} s_v>.
    Returns dict {(nx,ny): complex coeff} with |coeff| > tol.
    """
    acc = {}
    def add(key, val):
        acc[key] = acc.get(key, 0j) + val
    VAi_VB = A.Vi @ B.V
    for (a, b), s in zip(classes, sections):
        s = np.asarray(s, dtype=complex)
        if a and b:
            l = s.conj() @ A.V                    # row
            r = B.Vi @ s                          # col
            for j in range(A.d):
                for m in range(B.d):
                    add((int(A.w[j]), int(B.w[m])), l[j] * VAi_VB[j, m] * r[m])
        elif a:
            l = s.conj() @ A.V
            r = A.Vi @ s
            for j in range(A.d):
                add((int(A.w[j]), 0), l[j] * r[j])
        elif b:
            l = s.conj() @ B.V
            r = B.Vi @ s
            for m in range(B.d):
                add((0, int(B.w[m])), l[m] * r[m])
        else:
            add((0, 0), complex(np.vdot(s, s)))
    return {k: v for k, v in acc.items() if abs(v) > tol}

def modes_general(classes, sections, ops, tol=1e-12):
    """
    As `modes`, but with a PER-VERTEX pair ops[v] = (A_v, B_v) of OneParam
    objects.  This is what per-vertex charge requires: the fibre at v carries
    its own representation of the structure group, so there is no single Lambda.
    """
    acc = {}
    def add(key, val):
        acc[key] = acc.get(key, 0j) + val
    for (a, b), s, (A, B) in zip(classes, sections, ops):
        s = np.asarray(s, dtype=complex)
        if a and b:
            Mx = A.Vi @ B.V
            l = s.conj() @ A.V
            r = B.Vi @ s
            for j in range(A.d):
                for m in range(B.d):
                    add((int(A.w[j]), int(B.w[m])), l[j] * Mx[j, m] * r[m])
        elif a:
            l = s.conj() @ A.V; r = A.Vi @ s
            for j in range(A.d):
                add((int(A.w[j]), 0), l[j] * r[j])
        elif b:
            l = s.conj() @ B.V; r = B.Vi @ s
            for m in range(B.d):
                add((0, int(B.w[m])), l[m] * r[m])
        else:
            add((0, 0), complex(np.vdot(s, s)))
    return {k: v for k, v in acc.items() if abs(v) > tol}


def z_from_modes(md):
    """Vectorised evaluator z(X,Y) on numpy arrays."""
    keys = np.array(list(md.keys()), dtype=float)
    vals = np.array(list(md.values()), dtype=complex)
    def z(X, Y):
        X = np.asarray(X, dtype=float); Y = np.asarray(Y, dtype=float)
        out = np.zeros(np.broadcast(X, Y).shape, dtype=complex)
        for (nx, ny), c in zip(keys, vals):
            out = out + c * np.exp(1j * (nx * X + ny * Y))
        return out
    return z

def lattice_rank(points):
    """Rank of the subgroup of Z^2 generated by the DIFFERENCES of `points`."""
    pts = [np.array(p, dtype=float) for p in points]
    if len(pts) < 2:
        return 0
    diffs = np.array([p - pts[0] for p in pts[1:]])
    if not np.any(np.abs(diffs) > 1e-12):
        return 0
    return int(np.linalg.matrix_rank(diffs, tol=1e-8))

# ----------------------------------------------------------------- the rates

def lam_haar(md, M=2048):
    """Haar average of log|z| over the FULL torus T^2, midpoint rule, vectorised.
       Correct when (theta_F,theta_C) are generic so that the closure H = T^2."""
    g = (np.arange(M) + 0.5) * 2.0 * math.pi / M
    X, Y = np.meshgrid(g, g, indexing='ij')
    Z = z_from_modes(md)(X, Y)
    return float(np.mean(np.log(np.maximum(np.abs(Z), 1e-300))))

def lam_direct(md, thF, thC, N=400000):
    """Direct schedule average (1/N) SUM_{k=1..N} log|z(k thF, k thC)|.
       Assumes NOTHING about equidistribution."""
    k = np.arange(1, N + 1, dtype=float)
    Z = z_from_modes(md)(k * thF, k * thC)
    return float(np.mean(np.log(np.maximum(np.abs(Z), 1e-300))))

def support_fft(md, M=64, tol=1e-9):
    """Independent FFT re-derivation of supp(z), to cross-check `modes`."""
    g = np.arange(M) * 2.0 * math.pi / M
    X, Y = np.meshgrid(g, g, indexing='ij')
    arr = z_from_modes(md)(X, Y)
    Fc = np.fft.fft2(arr) / (M * M)
    out = []
    for i in range(M):
        for j in range(M):
            if abs(Fc[i, j]) > tol:
                nx = i if i <= M // 2 else i - M
                ny = j if j <= M // 2 else j - M
                out.append(((nx, ny), Fc[i, j]))
    return sorted(out)

# ------------------------------------------------------- Mahler cross-checks

_BERN = {0: 1.0, 1: -0.5, 2: 1/6, 4: -1/30, 6: 1/42, 8: -1/30, 10: 5/66,
         12: -691/2730, 14: 7/6, 16: -3617/510, 18: 43867/798, 20: -174611/330,
         22: 854513/138}

def _li2_series(z):
    """Li_2 by the Bernoulli series in u = -log(1-z).  Valid for |u| < 2 pi."""
    z = complex(z)
    u = -np.log(1.0 - z)
    s = 0j
    fact = 1.0
    for k in range(0, 23):
        fact = math.factorial(k + 1)
        b = _BERN.get(k, 0.0)
        if b:
            s += b * u ** (k + 1) / fact
    return s

def _li2(z):
    """Li_2(z), principal branch, via inversion + reflection + Bernoulli series.
       Recursion depth is bounded by 2 by construction."""
    z = complex(z)
    if abs(z) > 1.0:                      # inversion -> |1/z| < 1
        return -_li2_inner(1.0 / z) - math.pi ** 2 / 6 - 0.5 * np.log(-z) ** 2
    return _li2_inner(z)

def _li2_inner(z):
    z = complex(z)
    if abs(1.0 - z) < 0.5:                # z near 1: reflect, 1-z is then small
        return math.pi ** 2 / 6 - _li2_series(1.0 - z) - np.log(z) * np.log(1.0 - z)
    return _li2_series(z)

def bloch_wigner(zc):
    zc = complex(zc)
    if abs(zc) < 1e-300:
        return 0.0
    return _li2(zc).imag + math.atan2((1 - zc).imag, (1 - zc).real) * math.log(abs(zc))

def cassaigne_maillot(a, b, c):
    """m(a + b x + c y) for positive reals."""
    a, b, c = float(a), float(b), float(c)
    if a > b + c or b > a + c or c > a + b:
        return math.log(max(a, b, c))
    alpha = math.acos(max(-1.0, min(1.0, (b*b + c*c - a*a) / (2*b*c))))
    beta  = math.acos(max(-1.0, min(1.0, (a*a + c*c - b*b) / (2*a*c))))
    gamma = math.pi - alpha - beta
    zc = (a / b) * complex(math.cos(gamma), math.sin(gamma))
    return (bloch_wigner(zc) + alpha*math.log(a) + beta*math.log(b) + gamma*math.log(c)) / math.pi

