def independent(gens, n):
    """reduce to an independent generating set over F2 in symplectic representation."""
    rows = []
    keep = []
    for g in gens:
        vec = 0
        for k, ch in enumerate(g):
            if ch in 'XY':
                vec |= 1 << (2 * k)
            if ch in 'ZY':
                vec |= 1 << (2 * k + 1)
        cur = vec
        for r in rows:
            p = r.bit_length() - 1
            if cur >> p & 1:
                cur ^= r
        if cur:
            rows.append(cur); rows.sort(reverse=True); keep.append(g)
    return keep


def code_space(gens, n):
    N = 2 ** n
    H = np.zeros((N, N), complex)
    for g in gens:
        H -= pauli_mat(g)
    H = (H + H.conj().T) / 2
    ev, U = np.linalg.eigh(H)
    tol = 1e-8 * max(1.0, abs(ev).max())
    sel = np.abs(ev - ev[0]) < tol
    Q = U[:, sel]
    return H, Q, Q @ Q.conj().T, ev


def phi(V, Q):
    B = Q.conj().T @ V @ Q
    m = B.shape[0]
    return B - np.trace(B) / m * np.eye(m)


def first_order_rank(ops, Q, tol=1e-9):
    rows = []
    m = Q.shape[1]
    for V in ops:
        A = phi(V, Q)
        v = []
        for a in range(m):
            for b in range(a, m):
                if a == b:
                    v.append(A[a, a].real)
                else:
                    v.append(A[a, b].real); v.append(A[a, b].imag)
        rows.append(v)
    M = np.array(rows)
    s = np.linalg.svd(M, compute_uv=False)
    smax = s.max() if s.size else 0.0
    return int(np.sum(s > tol * max(1.0, smax))), float(smax)


def paulis_of_weight(n, w):
    out = []
    for supp in itertools.combinations(range(n), w):
        for letters in itertools.product('XYZ', repeat=w):
            s = ['I'] * n
            for k, ch in zip(supp, letters):
                s[k] = ch
            out.append(''.join(s))
    return out


def splitting(H, P0, m):
    ev, U = np.linalg.eigh(H)
    ov = np.einsum('ij,jk,ki->i', U.conj().T, P0, U).real
    idx = np.argsort(-ov)[:m]
    e = np.sort(ev[idx])
    return e[-1] - e[0]


def slope_fit(H0, V, P0, m, eps_list):
    xs, ys = [], []
    for eps in eps_list:
        s = splitting(H0 + eps * V, P0, m)
        if s > 1e-12:
            xs.append(np.log(eps)); ys.append(np.log(s))
    if len(xs) < 2:
        return float('nan'), 0.0, []
    A = np.polyfit(xs, ys, 1)
    res = float(np.max(np.abs(np.polyval(A, xs) - ys)))
    return A[0], res, list(zip(np.exp(xs), np.exp(ys)))


