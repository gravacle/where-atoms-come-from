"""LANE O-2/O-3, PART 2.  WHY THE FIRST-ORDER MATRIX ELEMENT VANISHES TO ORDER d-1.

Part 1 established the exact criterion for first-order splitting:
        E0 splits at first order under V  <=>  Phi(V) := PVP - (tr PVP/n) P  !=  0,
and that for a 0-form symmetry there is always a SINGLE-SITE V with Phi(V) != 0, because a 0-form
charge is a SUM OF LOCAL DENSITIES and some density must be non-scalar on the multiplet.

This part does the other half of the contrast.  The claim to be proved and measured:

  THEOREM (topological vanishing).  Let E0 be the code space of a stabiliser code of distance d, with
  H0 = -sum_j S_j so that E0 is the ground eigenspace with gap 2.  Let V_w = the real span of Pauli
  operators of weight <= w.  Then
        rank Phi restricted to V_w  =  0   for all  w < d,
  so NO perturbation of weight < d splits E0 at first order, generic or not; and the splitting obeys
        Delta(eps)  ~  eps^(ceil(d/w)),   in particular  Delta ~ eps^d  for single-site noise.

  PROOF OF THE VANISHING (this is the whole mechanism, in three lines).
    Let O be a Pauli of weight |O| < d.
      - if O ANTICOMMUTES with some stabiliser S_j, then P O P = P O P and S_j P = P, so
        P O P = P S_j O S_j P = - P O P = 0.  Scalar (namely 0).
      - if O COMMUTES with every stabiliser and lies IN the stabiliser group, P O P = +- P.  Scalar.
      - if O commutes with every stabiliser and is NOT in the stabiliser group, O is by definition an
        undetectable non-trivial logical operator, so |O| >= d.  EXCLUDED by |O| < d.
    Hence every Pauli of weight < d has P O P in C.P, so Phi = 0 on all of V_w for w < d.  QED
    THIS IS EXACTLY THE KNILL-LAFLAMME CONDITION.  "Distance d" and "no first-order splitting below
    weight d" are THE SAME STATEMENT, not two facts that happen to agree.

  WHY THE 0-FORM CASE CANNOT DO THIS.  The non-scalar operators on E0 are the logical operators.  In
  the topological case they are non-contractible LOOPS -- there is no local density whose sum they
  are.  In the 0-form case the non-scalar operator Q^a = sum_x q^a_x IS a sum of local densities, so
  one density is already non-scalar.  d = 1.  That single sentence is the whole contrast.

MEASURED HERE
  SELF-CHECK  brute-force the distance d of every code from its definition (minimum weight of an
              undetectable non-trivial Pauli) and check it against the code's known d.
  MEASURED 1  the first-order rank of Phi on V_w for w = 1..d, for each code.  Must be 0 below d.
  MEASURED 2  the splitting exponent under single-site noise.  Prediction: slope = d.
  POSITIVE CONTROL  a d = 1 code ([[3,1,1]] with a weight-1 logical) run through the identical
              pipeline.  It must give rank Phi > 0 at w = 1 and slope 1.  Without it, every zero
              below would be uncontrolled.
"""
import itertools
import numpy as np

rng = np.random.default_rng(4242)
I2 = np.eye(2, dtype=complex)
SX = np.array([[0, 1], [1, 0]], dtype=complex)
SY = np.array([[0, -1j], [1j, 0]], dtype=complex)
SZ = np.array([[1, 0], [0, -1]], dtype=complex)
PAULI = {'I': I2, 'X': SX, 'Y': SY, 'Z': SZ}


def pauli_mat(s):
    M = np.array([[1.0 + 0j]])
    for ch in s:
        M = np.kron(M, PAULI[ch])
    return M


def weight(s):
    return sum(1 for ch in s if ch != 'I')


def symp(a, b):
    """0 if the two Pauli strings commute, 1 if they anticommute."""
    c = 0
    for x, y in zip(a, b):
        if x != 'I' and y != 'I' and x != y:
            c ^= 1
    return c


def pauli_group_elems(n):
    return [''.join(p) for p in itertools.product('IXYZ', repeat=n)]


def stab_group(gens, n):
    """the abelian group generated by gens, as a set of Pauli strings ignoring phase."""
    mul = {}
    def m(a, b):
        out = []
        for x, y in zip(a, b):
            if x == 'I':
                out.append(y)
            elif y == 'I':
                out.append(x)
            elif x == y:
                out.append('I')
            else:
                out.append({'XY': 'Z', 'YX': 'Z', 'XZ': 'Y', 'ZX': 'Y', 'YZ': 'X', 'ZY': 'X'}[x + y])
        return ''.join(out)
    S = {'I' * n}
    frontier = ['I' * n]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                b = m(a, g)
                if b not in S:
                    S.add(b); nxt.append(b)
        frontier = nxt
    return S


def brute_distance(gens, n):
    """min weight of a Pauli that commutes with every generator but is NOT in the stabiliser group."""
    S = stab_group(gens, n)
    best = None
    witness = None
    for p in pauli_group_elems(n):
        if p == 'I' * n:
            continue
        if all(symp(p, g) == 0 for g in gens) and p not in S:
            w = weight(p)
            if best is None or w < best:
                best, witness = w, p
    return best, witness, len(S)


