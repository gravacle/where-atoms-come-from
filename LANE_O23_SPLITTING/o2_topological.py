def toric_2x2_generators():
    """8 qubits on the links of a 2x2 periodic square lattice.
    link index: h(i,j) = j*2+i  (0..3),  v(i,j) = 4 + j*2+i  (4..7)."""
    h = lambda i, j: (j % 2) * 2 + (i % 2)
    v = lambda i, j: 4 + (j % 2) * 2 + (i % 2)
    gens = []
    for j in range(2):
        for i in range(2):
            # vertex operator: X on the four links touching vertex (i,j)
            links = [h(i, j), h(i - 1, j), v(i, j), v(i, j - 1)]
            s = ['I'] * 8
            for L in links:
                s[L] = 'X' if s[L] == 'I' else 'I'    # a link touched twice cancels (2x2 lattice)
            gens.append(''.join(s))
            # plaquette operator: Z on the four links around plaquette (i,j)
            links = [h(i, j), v(i + 1, j), h(i, j + 1), v(i, j)]
            s = ['I'] * 8
            for L in links:
                s[L] = 'Z' if s[L] == 'I' else 'I'
            gens.append(''.join(s))
    # keep an independent generating set
    return gens


