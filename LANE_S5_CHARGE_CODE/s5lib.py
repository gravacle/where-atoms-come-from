class CW:
    def __init__(self, name, nV, edges, faces):
        self.name = name
        self.nV = nV
        self.edges = list(edges)                 # [(s,t), ...]
        self.faces = [dict(f) for f in faces]    # [{e: mult}, ...]
        self.nE = len(self.edges)
        self.nF = len(self.faces)
        self.d1 = np.zeros((self.nV, self.nE), dtype=np.int64)
        for e, (s, t) in enumerate(self.edges):
            self.d1[s, e] -= 1
            self.d1[t, e] += 1
        self.d2 = np.zeros((self.nE, self.nF), dtype=np.int64)
        for f, ch in enumerate(self.faces):
            for e, m in ch.items():
                self.d2[e, f] += m
        assert np.all(self.d1 @ self.d2 == 0), f"{name}: d1 d2 != 0"

    # ranks over Q via numpy SVD-based matrix_rank on float copies (no torsion in this corpus)
    def betti(self):
        r1 = np.linalg.matrix_rank(self.d1.astype(float)) if self.nE else 0
        r2 = np.linalg.matrix_rank(self.d2.astype(float)) if self.nF else 0
        b0 = self.nV - r1
        b1 = (self.nE - r1) - r2
        b2 = self.nF - r2
        chi = self.nV - self.nE + self.nF
        assert chi == b0 - b1 + b2, f"{self.name}: chi mismatch"
        return dict(V=self.nV, E=self.nE, F=self.nF, chi=chi, b0=b0, b1=b1, b2=b2,
                    rank_d1=r1, rank_d2=r2,
                    gauge_params=self.nV - b0,
                    invariants=self.nE - (self.nV - b0),
                    curvature=r2, flat=b1)

    def chain_vec(self, chain):
        v = np.zeros(self.nE, dtype=np.int64)
        for e, m in chain.items():
            v[e] += m
        return v

    def is_cycle(self, chain):
        return np.all(self.d1 @ self.chain_vec(chain) == 0)

    def bounds(self, chain):
        """Is the chain in the image of d2 over Q?"""
        if self.nF == 0:
            return False
        b = self.chain_vec(chain).astype(float)
        A = self.d2.astype(float)
        r = np.linalg.matrix_rank(A)
        rA = np.linalg.matrix_rank(np.column_stack([A, b]))
        return r == rA

    def vertex_support(self, chain):
        vs = set()
        for e, m in chain.items():
            if m != 0:
                s, t = self.edges[e]
                vs.add(s); vs.add(t)
        return vs

    def classes(self, gF, gC):
        """returns a_v, b_v arrays in {0,1}"""
        sF = self.vertex_support(gF)
        sC = self.vertex_support(gC) if gC is not None else set()
        a = np.array([1 if v in sF else 0 for v in range(self.nV)], dtype=np.int64)
        b = np.array([1 if v in sC else 0 for v in range(self.nV)], dtype=np.int64)
        return a, b


