"""
s5lib.py -- CHARGE LANE library, written from scratch for the S5-CHARGE lane of
"Where Atoms Come From".  python3.9 + numpy only (no scipy/sympy/mpmath used).

CONVENTIONS PUBLISHED HERE (custody: nothing enters a governing clause without a pointer)

  * A carrier is a finite oriented regular CW complex of dim <= 2, given by
        vertices  V  (list of names)
        edges     E  (list of (src_index, tgt_index))
        faces     F  (list of dict {edge_index: signed multiplicity})
    d1 is V x E with d1[v,e] = +1 if v = tgt(e), -1 if v = src(e), 0 else
       (a vertex that is both src and tgt of a loop edge gets 0; no such edge is used).
    d2 is E x F with d2[e,f] = the signed multiplicity of e in the boundary chain of f.
    d1 @ d2 = 0 is asserted on every carrier.

  * A designated loop is a signed edge chain (dict edge_index -> int).  Its VERTEX SUPPORT
    is { v : v is an endpoint of some edge appearing in the chain with nonzero coefficient }.
    (This is W-01's operator convention: (M_gamma s)(v) = W(gamma) s(v) for v ON gamma.)

  * CHARGE.  q_v is an integer attached to the FIBRE at v.  U(1) acts on L_v by z -> z^{q_v},
    so the holonomy W(gamma) acts on L_v as W(gamma)^{q_v}.  Hence the EXPONENT VECTOR
        E_v = q_v * (a_v, b_v)  in  Z^2 ,     a_v = [v on gamma_F], b_v = [v on gamma_C].
    Unit charge (q_v = 1 for all v) recovers S4's four corners of the unit square.

  * FORMATION FUNCTIONAL.  With u = conj(W_F) = e^{-i f}, v = W_C = e^{i c},
        Z_k = sum_v p_v u^{k m_v} v^{k n_v} = sum_v p_v exp( i k ( -m_v f + n_v c ) ).
    theta := (theta_u, theta_v) = (-f, c) is the coordinate used throughout.

  * lambda_A = log|Z_1|            (schedule A, uniform clock k_n = 1)
    lambda_B = lim (1/N) sum_{n<=N} log|Z_n|   (schedule B, canonical clock k_n = n)

  * RELATION LATTICE  L = { (m,n) in Z^2 : u^m v^n = 1 } = { (m,n) : -m f + n c = 0 mod 2pi }.
  * DIFFERENCE LATTICE Delta(S) = subgroup of Z^2 generated by { E_x - E_y : x,y in supp(p) }.
  * FORMATION GROUP    G = phi(Delta) = Delta / (Delta ^ L)   where phi(m,n) = u^m v^n.

  * SEEDS: every random draw in this lane uses numpy.random.default_rng(SEED) with SEED
    printed at the call site.  No global/implicit seeding anywhere.
"""

