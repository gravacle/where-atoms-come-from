def exponents_from_charge(a, b, q):
    """E_v = q_v * (a_v, b_v)."""
    q = np.asarray(q, dtype=np.int64)
    return np.stack([q * a, q * b], axis=1)          # shape (V,2)

def support_exponents(E, p, tol=0.0):
    keep = np.asarray(p) > tol
    return np.asarray(E)[keep], np.asarray(p)[keep]

# ---- integer lattice utilities (exact, integer arithmetic only) ----

def _igcd(a, b):
    a, b = abs(int(a)), abs(int(b))
    while b:
        a, b = b, a % b
    return a

def hnf2(vectors):
    """Hermite normal form (row style) of the subgroup of Z^2 generated by `vectors`.
    Returns a tuple of 0,1 or 2 basis rows in a canonical form -> usable as a dict key."""
    rows = [tuple(int(x) for x in v) for v in vectors if any(int(x) != 0 for x in v)]
    if not rows:
        return ()
    # column-echelon by repeated gcd on first coordinate
    A = [list(r) for r in rows]
    # reduce first column
    while True:
        nz = [r for r in A if r[0] != 0]
        if len(nz) <= 1:
            break
        nz.sort(key=lambda r: abs(r[0]))
        piv = nz[0]
        changed = False
        for r in A:
            if r is piv or r[0] == 0:
                continue
            k = r[0] // piv[0]
            r[0] -= k * piv[0]
            r[1] -= k * piv[1]
            changed = True
        if not changed:
            break
    piv = None
    for r in A:
        if r[0] != 0:
            piv = r
            break
    rest = [r for r in A if r[0] == 0 and r[1] != 0]
    g = 0
    for r in rest:
        g = _igcd(g, r[1])
    basis = []
    if piv is not None:
        if piv[0] < 0:
            piv = [-piv[0], -piv[1]]
        if g:
            piv = [piv[0], piv[1] % g]
        basis.append(tuple(piv))
    if g:
        basis.append((0, g))
    return tuple(basis)

def lattice_rank(vectors):
    return len(hnf2(vectors))

def lattice_index(vectors):
    """|Z^2 : Lambda| if rank 2, else None."""
    B = hnf2(vectors)
    if len(B) != 2:
        return None
    return abs(B[0][0] * B[1][1] - B[0][1] * B[1][0])

def difference_lattice(Esup):
    """Delta(S), as an HNF basis tuple."""
    E = np.asarray(Esup)
    if len(E) == 0:
        return ()
    diffs = [E[i] - E[0] for i in range(1, len(E))]
    return hnf2(diffs)

def unimodular_completion(d):
    """Given a primitive (m,n), return M in GL2(Z) with M @ d = (1,0)^T."""
    m, n = int(d[0]), int(d[1])
    g = _igcd(m, n)
    assert g == 1, "not primitive"
    # extended euclid: x*m + y*n = 1
    old_r, r = m, n
    old_s, s = 1, 0
    old_t, t = 0, 1
    while r != 0:
        qq = old_r // r
        old_r, r = r, old_r - qq * r
        old_s, s = s, old_s - qq * s
        old_t, t = t, old_t - qq * t
    x, y = old_s, old_t          # x*m + y*n = gcd = +-1
    if old_r < 0:
        x, y, old_r = -x, -y, -old_r
    M = np.array([[x, y], [-n, m]], dtype=np.int64)
    assert abs(int(round(np.linalg.det(M.astype(float))))) == 1
    assert tuple(M @ np.array([m, n])) == (1, 0)
    return M

def primitive(d):
    g = _igcd(d[0], d[1])
    return (d[0] // g, d[1] // g), g


