def Z_of_k(k, E, p, f, c):
    """closed form.  k may be an array."""
    E = np.asarray(E); p = np.asarray(p, dtype=float)
    th = np.array([-f, c], dtype=float)
    ph = E @ th                                    # (V,)
    k = np.atleast_1d(np.asarray(k, dtype=float))
    return (np.exp(1j * np.outer(k, ph)) * p).sum(axis=1)

def Z_of_k_matrix(k, a, b, q, p_or_s, f, c):
    """direct matrix action on C^V, no closed form used.
    p_or_s : a complex section s (arbitrary phases) -- p_v = |s_v|^2, must be normalised."""
    s = np.asarray(p_or_s, dtype=complex)
    WF = np.exp(1j * f); WC = np.exp(1j * c)
    q = np.asarray(q, dtype=np.int64)
    MF = np.diag(WF ** (q * np.asarray(a)))
    MC = np.diag(WC ** (q * np.asarray(b)))
    x = np.linalg.matrix_power(MF, int(k)) @ s
    y = np.linalg.matrix_power(MC, int(k)) @ s
    return np.vdot(x, y)

def lambda_A(E, p, f, c):
    return float(np.log(np.abs(Z_of_k(1, E, p, f, c))[0]))

def lambda_B_direct(E, p, f, c, N=2_000_000, chunk=200_000):
    """(1/N) sum_{n=1}^N log|Z_n|.  Phases accumulated by exact integer n times float theta."""
    E = np.asarray(E); p = np.asarray(p, dtype=float)
    th = np.array([-f, c], dtype=float)
    ph = E @ th
    tot = 0.0
    n0 = 1
    while n0 <= N:
        n1 = min(N, n0 + chunk - 1)
        ns = np.arange(n0, n1 + 1, dtype=np.float64)
        Zs = (np.exp(1j * np.outer(ns, ph)) * p).sum(axis=1)
        tot += np.log(np.abs(Zs)).sum()
        n0 = n1 + 1
    return tot / N


