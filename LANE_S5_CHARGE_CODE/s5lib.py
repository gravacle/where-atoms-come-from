def mahler1(coef_by_exp):
    """m(P) for P(z) = sum coef z^exp, exponents integers (may be negative:
    multiplying by z^k does not change m).  Exact up to numpy.roots."""
    items = [(int(e), complex(cv)) for e, cv in coef_by_exp.items() if abs(cv) > 0]
    if not items:
        return -np.inf
    emin = min(e for e, _ in items)
    emax = max(e for e, _ in items)
    deg = emax - emin
    co = np.zeros(deg + 1, dtype=complex)
    for e, cv in items:
        co[e - emin] += cv
    co = co[::-1]                                     # numpy.roots wants highest first
    while len(co) > 1 and abs(co[0]) == 0:
        co = co[1:]
    if len(co) == 1:
        return float(np.log(abs(co[0])))
    r = np.roots(co)
    return float(np.log(abs(co[0])) + np.sum(np.log(np.maximum(1.0, np.abs(r)))))

def mahler2(coef_by_exp2, Nx=4096):
    """m(P) for P(x,y) = sum coef x^m y^n.  EXACT (Jensen) in y, midpoint quadrature in x
    with Nx nodes.  Nx is published at every call site."""
    items = [((int(m), int(n)), complex(cv)) for (m, n), cv in coef_by_exp2.items() if abs(cv) > 0]
    ts = (np.arange(Nx) + 0.5) / Nx
    xs = np.exp(2j * np.pi * ts)
    tot = 0.0
    ny = sorted(set(n for (m, n), _ in items))
    for x in xs:
        d = {}
        for (m, n), cv in items:
            d[n] = d.get(n, 0j) + cv * (x ** m)
        tot += mahler1(d)
    return tot / Nx

def mahler_generic(Esup, psup, Nx=4096):
    """m of the weight polynomial, i.e. lambda_B at a GENERIC (rank L = 0) connection.
    Reduces exactly to a 1-variable Mahler measure when rank Delta <= 1."""
    E = np.asarray(Esup); p = np.asarray(psup, dtype=float)
    E = E - E[0]                                       # translation: |Z| unchanged
    B = difference_lattice(E)
    if len(B) == 0:
        return 0.0
    if len(B) == 1:
        d, _ = primitive(B[0])
        M = unimodular_completion(d)
        F = (M @ E.T).T                                # second coordinate must vanish
        assert np.all(F[:, 1] == 0), F
        dd = {}
        for i in range(len(p)):
            dd[int(F[i, 0])] = dd.get(int(F[i, 0]), 0.0) + p[i]
        return mahler1(dd)
    dd = {}
    for i in range(len(p)):
        key = (int(E[i, 0]), int(E[i, 1]))
        dd[key] = dd.get(key, 0.0) + p[i]
    return mahler2(dd, Nx=Nx)

def lambda_B_exact(Esup, psup, L_basis, Nx=4096):
    """lambda_B = int_{L^perp} log|Z| dHaar, for an arbitrary exponent configuration and an
    arbitrary relation lattice L (given by an HNF basis tuple, () for rank 0).
      rank L = 0 : full torus  -> mahler_generic
      rank L = 1 : L = e*<d>, d primitive -> mean of e one-variable Mahler measures
      rank L = 2 : finite group -> exact finite average
    """
    E = np.asarray(Esup) - np.asarray(Esup)[0]
    p = np.asarray(psup, dtype=float)
    if len(L_basis) == 0:
        return mahler_generic(E, p, Nx=Nx)
    if len(L_basis) == 1:
        d, e = primitive(L_basis[0])
        M = unimodular_completion(d)                  # M d = (1,0)
        # characters of Z^2 restricted to L^perp:  L = e*Z*d.  In the M-basis, exponent
        # vector alpha = (M^{-T}) ... we instead push the EXPONENTS through (M^{-1})^T = ?
        # Cleanest: use the pairing <E, x>.  Substitute x = M^T y  =>  <E, M^T y> = <M E, y>.
        # M^T is a measure preserving automorphism of T^2 and maps the annihilator of e*<d>
        # to { y : e*y_1 = 0 } = mu_e x U(1).
        Fv = (M @ E.T).T
        tot = 0.0
        for j in range(e):
            zeta = np.exp(2j * np.pi * j / e)
            dd = {}
            for i in range(len(p)):
                key = int(Fv[i, 1])
                dd[key] = dd.get(key, 0j) + p[i] * zeta ** int(Fv[i, 0])
            tot += mahler1(dd)
        return tot / e
    # rank 2 : the quotient Z^2/L is finite; H = its dual, a finite group.  Enumerate.
    B = np.array(L_basis, dtype=np.int64)
    idx = abs(int(B[0, 0] * B[1, 1] - B[0, 1] * B[1, 0]))
    # enumerate H = { (s,t) in (1/idx)Z^2 mod 1 : <(m,n),(s,t)> in Z for all (m,n) in L }
    pts = []
    D = idx
    for s in range(D):
        for t in range(D):
            ok = all((B[r, 0] * s + B[r, 1] * t) % D == 0 for r in range(2))
            if ok:
                pts.append((s / D, t / D))
    assert len(pts) == D, (len(pts), D)
    tot = 0.0
    for (s, t) in pts:
        ph = 2 * np.pi * (E[:, 0] * s + E[:, 1] * t)
        tot += float(np.log(abs((p * np.exp(1j * ph)).sum())))
    return tot / len(pts)

def relation_lattice(f, c, max_den=None, exact_pair=None):
    """L for a connection.  If exact_pair = (Fraction pf, Fraction pc) is given with
    f = 2 pi pf, c = 2 pi pc, L is computed EXACTLY in integer arithmetic.
    Otherwise returns () (treated as generic)."""
    if exact_pair is None:
        return ()
    pf, pc = exact_pair
    # L = { (m,n) : -m pf + n pc  in  Z }
    den = np.lcm(pf.denominator, pc.denominator)
    A = int(-pf * den), int(pc * den)                 # -m A0 ... : condition m*A0 + n*A1 = 0 mod den
    sols = []
    # the set { (m,n) : m*A0 + n*A1 = 0 mod den } is a finite-index sublattice of Z^2
    for m in range(den):
        for n in range(den):
            if (m * A[0] + n * A[1]) % den == 0:
                sols.append((m, n))
    sols += [(den, 0), (0, den)]
    return hnf2(sols)
