def lat_members(basis, R=14):
    """Reference: the set of lattice points in [-R,R]^2 generated by `basis`, by enumeration."""
    S = {(0, 0)}
    if len(basis) == 1:
        (a, b) = basis[0]
        for t in range(-4 * R, 4 * R + 1):
            p = (t * a, t * b)
            if abs(p[0]) <= R and abs(p[1]) <= R:
                S.add(p)
    elif len(basis) == 2:
        (a, b), (c, d) = basis
        for s in range(-4 * R, 4 * R + 1):
            for t in range(-4 * R, 4 * R + 1):
                p = (s * a + t * c, s * b + t * d)
                if abs(p[0]) <= R and abs(p[1]) <= R:
                    S.add(p)
    return S


def gens_members(gens, R=14):
    """Reference: lattice generated by an arbitrary generating set, by closure enumeration."""
    S = {(0, 0)}
    frontier = {(0, 0)}
    G = [g for g in gens if g != (0, 0)]
    while frontier:
        nxt = set()
        for p in frontier:
            for g in G:
                for sg in (+1, -1):
                    q = (p[0] + sg * g[0], p[1] + sg * g[1])
                    if abs(q[0]) <= R and abs(q[1]) <= R and q not in S:
                        S.add(q)
                        nxt.add(q)
        frontier = nxt
    return S


def inner(S, r):
    return {p for p in S if abs(p[0]) <= r and abs(p[1]) <= r}


