seen = {}
for M in ker:
    for c, P in LAB.items():
        for ph, phn in ((1, '+1'), (-1, '-1'), (1j, '+i'), (-1j, '-i')):
            if np.linalg.norm(M - ph * P) < 1e-8:
                seen.setdefault(names.get(c, str(c)), set()).add(phn)
say(f"   holonomy elements found: " +
    ", ".join(f"{nm} x {{{','.join(sorted(v))}}}" for nm, v in sorted(seen.items())))
say("   EXACTLY: HOLONOMY GROUP = <R1, R2> x PHASES.  THE HOLONOMY OF A WRITE-LOOP IS A PRODUCT")
