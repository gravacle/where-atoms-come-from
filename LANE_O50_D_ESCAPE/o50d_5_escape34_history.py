def evolve(rho_sys):
    r0 = np.kron(rho_sys, rB0)
    Uc = Ut.conj().T @ r0 @ Ut
    return Ut @ (ph[:, None] * Uc * ph.conj()[None, :]) @ Ut.conj().T
def bath_obs(r, B):
    rB = r.reshape(N, nB, N, nB).trace(axis1=0, axis2=2)
    return float(np.real(np.trace(rB @ B)))
