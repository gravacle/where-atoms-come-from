import numpy as np

np.set_printoptions(precision=6, suppress=True, linewidth=160)


# ----------------------------------------------------------------------------------
# LEMMA 0 (used everywhere below).  For R Hermitian, [L,R]=0  <=>  [L^dag,R]=0.
#   ([L,R])^dag = R^dag L^dag - L^dag R^dag = R L^dag - L^dag R = [R, L^dag].
# So clause (ii) forces R into the commutant of the *-ALGEBRA generated by
# {I, H, L_k, L_k^dag}, not merely of the set {H, L_k}.  This is the whole of gap (a).
# ----------------------------------------------------------------------------------


def commutant_basis(ops, d, tol=1e-9):
    """Orthonormal (Hilbert-Schmidt) basis of {X in C^{dxd} : [X,O]=0 for all O in ops}.

    Returns (basis_list, dim).  dim is the COMPLEX dimension.
    Because we always pass a *-closed set of ops, the commutant is *-closed and the
    Hermitian elements form a REAL vector space of the same dimension.
    """
    I = np.eye(d)
    rows = []
    for O in ops:
        # row-major vec: vec(A X B) = (A (x) B^T) vec(X)
        M = np.kron(I, O.T) - np.kron(O, I)
        rows.append(M)
    if not rows:
        A = np.zeros((1, d * d), dtype=complex)
    else:
        A = np.vstack(rows)
    # null space via SVD
    _, s, vh = np.linalg.svd(A)
    s_full = np.zeros(d * d)
    s_full[: len(s)] = s
    null = vh[s_full <= tol * max(1.0, s_full.max() if s_full.size else 1.0)]
    basis = [v.reshape(d, d) for v in null.conj()]
    return basis, len(basis)


def star_closure(ops):
    out = []
    for O in ops:
        out.append(O)
        out.append(O.conj().T)
    return out


def hermitian_commutant(ops, d, tol=1e-9):
    """Real-orthonormal basis of the HERMITIAN elements of the commutant."""
    b, k = commutant_basis(star_closure(ops), d, tol)
    herm = []
    for X in b:
        herm.append((X + X.conj().T) / 2.0)
        herm.append((X - X.conj().T) / (2.0j))
    # real-orthonormalise under <A,B> = Re Tr(A^dag B)
    out = []
    for X in herm:
        for Y in out:
            X = X - np.real(np.trace(Y.conj().T @ X)) * Y
        n = np.sqrt(np.real(np.trace(X.conj().T @ X)))
        if n > 1e-8:
            out.append(X / n)
    return out


def generated_algebra(ops, d, tol=1e-9, maxit=40):
    """HS-orthonormal basis of the *-algebra generated by {I} u ops u ops^dag."""
    seeds = [np.eye(d, dtype=complex)] + list(star_closure(ops))

    def add(basis, X):
        for Y in basis:
            X = X - np.trace(Y.conj().T @ X) * Y
        n = np.sqrt(abs(np.trace(X.conj().T @ X)))
        if n > 1e-7:
            basis.append(X / n)
            return True
        return False

    basis = []
    for X in seeds:
        add(basis, X)
    for _ in range(maxit):
        grew = False
        cur = list(basis)
        for A in cur:
            for B in cur:
                if add(basis, A @ B):
                    grew = True
        if not grew:
            break
    return basis


def compress(basis, P_cols):
    """Compress a list of operators to the subspace spanned by the columns of P_cols."""
    return [P_cols.conj().T @ X @ P_cols for X in basis]


def span_dim(mats, tol=1e-8):
    if not mats:
        return 0
    V = np.array([m.ravel() for m in mats])
    return int(np.linalg.matrix_rank(V, tol=tol))


def eigenspaces(H, tol=1e-8):
    """[(eigenvalue, columns spanning the eigenspace)] for Hermitian H."""
    w, v = np.linalg.eigh(H)
    out = []
    i = 0
    while i < len(w):
        j = i
        while j + 1 < len(w) and abs(w[j + 1] - w[i]) < tol:
            j += 1
        out.append((float(w[i]), v[:, i : j + 1]))
        i = j + 1
    return out


def record_search(H, Ls, tol=1e-8, seed=0):
    """Search for R satisfying (i) bit, (ii) durable, (iii) non-trivial.

    Returns dict with the Hermitian-commutant dimension, and an explicit R if found.
    Strategy: R must lie in the commutant A' of the *-algebra A = alg{I,H,L_k,L_k^dag}.
    Take a random Hermitian element of A', cluster its spectrum, and form the spectral
    projections -- these lie in A' too.  Any non-trivial one gives R = I - 2Q.
    """
    d = H.shape[0]
    ops = [H] + list(Ls)
    hb = hermitian_commutant(ops, d, tol)
    res = {"herm_commutant_dim": len(hb), "R": None, "lambda": None}
    if len(hb) <= 1:
        return res
    rng = np.random.default_rng(seed)
    for attempt in range(20):
        c = rng.normal(size=len(hb))
        X = sum(ci * Bi for ci, Bi in zip(c, hb))
        X = (X + X.conj().T) / 2
        w, v = np.linalg.eigh(X)
        # cluster
        groups, cur = [], [0]
        for i in range(1, d):
            if abs(w[i] - w[i - 1]) < 1e-7:
                cur.append(i)
            else:
                groups.append(cur)
                cur = [i]
        groups.append(cur)
        if len(groups) < 2:
            continue
        for split in range(1, len(groups)):
            idx = [i for g in groups[:split] for i in g]
            Q = v[:, idx] @ v[:, idx].conj().T
            R = np.eye(d) - 2 * Q
            # verify (i),(ii)
            if np.linalg.norm(R @ R - np.eye(d)) > 1e-8:
                continue
            if np.linalg.norm(R - R.conj().T) > 1e-8:
                continue
            if np.linalg.norm(H @ R - R @ H) > 1e-7:
                continue
            if any(np.linalg.norm(L @ R - R @ L) > 1e-7 for L in Ls):
                continue
            # (iii): non-constant on SOME eigenspace of H
            for lam, cols in eigenspaces(H):
                if cols.shape[1] < 2:
                    continue
                Rl = cols.conj().T @ R @ cols
                if np.linalg.norm(Rl - np.trace(Rl) / cols.shape[1] * np.eye(cols.shape[1])) > 1e-7:
                    res["R"] = R
                    res["lambda"] = lam
                    return res
    return res


def record_search_on(H, Ls, lam_index, tol=1e-8, seed=0):
    """Same as record_search but the record must be non-constant on the CHOSEN eigenspace."""
    d = H.shape[0]
    hb = hermitian_commutant([H] + list(Ls), d, tol)
    es = eigenspaces(H)
    lam, cols = es[lam_index]
    m = cols.shape[1]
    out = {"herm_commutant_dim": len(hb), "R": None, "lambda": lam, "m": m}
    if len(hb) <= 1 or m < 2:
        return out
    rng = np.random.default_rng(seed)
    for _ in range(30):
        c = rng.normal(size=len(hb))
        X = sum(ci * Bi for ci, Bi in zip(c, hb))
        X = (X + X.conj().T) / 2
        w, v = np.linalg.eigh(X)
        groups, cur = [], [0]
        for i in range(1, d):
            if abs(w[i] - w[i - 1]) < 1e-7:
                cur.append(i)
            else:
                groups.append(cur)
                cur = [i]
        groups.append(cur)
        for split in range(1, len(groups)):
            idx = [i for g in groups[:split] for i in g]
            Q = v[:, idx] @ v[:, idx].conj().T
            R = np.eye(d) - 2 * Q
            if np.linalg.norm(R @ R - np.eye(d)) > 1e-8:
                continue
            if np.linalg.norm(H @ R - R @ H) > 1e-7:
                continue
            if any(np.linalg.norm(L @ R - R @ L) > 1e-7 for L in Ls):
                continue
            Rl = cols.conj().T @ R @ cols
            if np.linalg.norm(Rl - np.trace(Rl) / m * np.eye(m)) > 1e-7:
                out["R"] = R
                return out
    return out


def clause_report(H, Ls, R, name=""):
    """Numerical values of clauses (i)-(iv).  (v) needs a locality structure; see note."""
    d = H.shape[0]
    c1a = np.linalg.norm(R - R.conj().T)
    c1b = np.linalg.norm(R @ R - np.eye(d))
    c2 = max([np.linalg.norm(H @ R - R @ H)] + [np.linalg.norm(L @ R - R @ L) for L in Ls])
    c3 = 0.0
    for lam, cols in eigenspaces(H):
        m = cols.shape[1]
        if m < 2:
            continue
        Rl = cols.conj().T @ R @ cols
        c3 = max(c3, float(np.linalg.norm(Rl - np.trace(Rl) / m * np.eye(m))))
    tr = float(np.real(np.trace(R)))
    print(f"  {name:38s} (i) {c1a:.2e}/{c1b:.2e}  (ii) {c2:.2e}  (iii) {c3:.4f}  Tr R = {tr:+.4f}")
    return dict(i=max(c1a, c1b), ii=c2, iii=c3, trace=tr)


# ==================================================================================
#  SELF-CHECKS -- every expected value is known independently of this code.
