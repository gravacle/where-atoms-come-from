def selfchecks():
    ok = True

    def chk(label, got, want):
        nonlocal ok
        good = (got == want)
        ok = ok and good
        print(f"  [{'PASS' if good else 'FAIL'}] {label:62s} got {got:6d}  want {want:6d}")

    print("SELF-CHECKS (commutant dimensions; all expected values known independently)")

    # 1. no constraints at all -> full matrix algebra
    chk("commutant of {I} on d=5 is all of M_5", commutant_basis([np.eye(5)], 5)[1], 25)

    # 2. one Hermitian with distinct eigenvalues -> the diagonal algebra, dim d
    rng = np.random.default_rng(1)
    A = rng.normal(size=(6, 6)) + 1j * rng.normal(size=(6, 6))
    A = A + A.conj().T
    chk("commutant of a generic Hermitian on d=6 is the diagonal, dim 6",
        commutant_basis([A], 6)[1], 6)

    # 3. Pauli: commutant of alg{XX, ZZ} on 2 qubits = span{II,XX,YY,ZZ}, dim 4
    X = np.array([[0, 1], [1, 0]], dtype=complex)
    Y = np.array([[0, -1j], [1j, 0]])
    Z = np.array([[1, 0], [0, -1]], dtype=complex)
    XX, ZZ = np.kron(X, X), np.kron(Z, Z)
    chk("commutant of alg{XX,ZZ} on 2 qubits = span{II,XX,YY,ZZ}",
        commutant_basis([XX, ZZ], 4)[1], 4)

    # 4. SU(2) on 2 spin-1/2: 0 (x) 1, multiplicities 1,1 -> dim A' = 1^2+1^2 = 2
    def spin_ops(n):
        sx, sy, sz = X / 2, Y / 2, Z / 2
        J = [np.zeros((2 ** n, 2 ** n), dtype=complex) for _ in range(3)]
        for i in range(n):
            for a, s in enumerate((sx, sy, sz)):
                op = np.eye(1, dtype=complex)
                for j in range(n):
                    op = np.kron(op, s if j == i else np.eye(2))
                J[a] += op
        return J

    chk("commutant of SU(2) on 2 spins = 1^2+1^2 = 2", commutant_basis(spin_ops(2), 4)[1], 2)

    # 5. SU(2) on 3 spin-1/2: 3/2 (x1) + 1/2 (x2) -> dim A' = 1^2 + 2^2 = 5
    chk("commutant of SU(2) on 3 spins = 1^2+2^2 = 5", commutant_basis(spin_ops(3), 8)[1], 5)

    # 6. A = I_3 (x) M_2  ->  A' = M_3 (x) I_2, dim 9
    B1 = rng.normal(size=(2, 2)) + 1j * rng.normal(size=(2, 2))
    B2 = rng.normal(size=(2, 2)) + 1j * rng.normal(size=(2, 2))
    ops6 = [np.kron(np.eye(3), B1), np.kron(np.eye(3), B2)]
    chk("commutant of I_3 (x) M_2 is M_3 (x) I_2, dim 9",
        commutant_basis(star_closure(ops6), 6)[1], 9)

    # 7. Hermitian commutant has the SAME dimension over R as the commutant over C
    hb = hermitian_commutant(spin_ops(3), 8)
    chk("dim_R(Hermitian part of A') = dim_C(A') for SU(2) on 3 spins", len(hb), 5)

    # 8. generated algebra: alg{XX,ZZ} = span{II,XX,YY,ZZ}, dim 4
    chk("dim alg{XX,ZZ} = 4", len(generated_algebra([XX, ZZ], 4)), 4)

    # 9. generated algebra of a generic pair on d=4 is all of M_4
    G1 = rng.normal(size=(4, 4)) + 1j * rng.normal(size=(4, 4))
    chk("dim alg{generic G, G^dag} on d=4 = 16", len(generated_algebra([G1], 4)), 16)

    # 10. LEMMA 0 numerically: [L,R]=0 => [L^dag,R]=0 for Hermitian R
    R = np.diag([1, 1, -1, -1]).astype(complex)
    L = np.kron(np.eye(2), rng.normal(size=(2, 2)) + 1j * rng.normal(size=(2, 2)))
    lem = np.linalg.norm(L @ R - R @ L) < 1e-12 and np.linalg.norm(L.conj().T @ R - R @ L.conj().T) < 1e-12
    print(f"  [{'PASS' if lem else 'FAIL'}] LEMMA 0: [L,R]=0 and [L^dag,R]=0 together"
          f"{'':22s}")
    ok = ok and lem

    print(f"\nSELF-CHECKS: {'ALL PASS' if ok else 'SOME FAILED -- STOP'}")
    return ok


if __name__ == "__main__":
    good = selfchecks()
    raise SystemExit(0 if good else 1)
