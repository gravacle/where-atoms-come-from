def build_flipper(R, tol=1e-9):
    """If Tr R = 0, return U with U^dag R U = -R; else None."""
    d = R.shape[0]
    w, v = np.linalg.eigh(R)
    plus = v[:, w > 0]
    minus = v[:, w < 0]
    if plus.shape[1] != minus.shape[1]:
        return None
    U = plus @ minus.conj().T + minus @ plus.conj().T
    return U


def commutative_minimal_projections(hb, tol=1e-7):
    """Minimal projections of a COMMUTATIVE Hermitian commutant basis hb.  Returns ranks."""
    d = hb[0].shape[0]
    rng = np.random.default_rng(0)
    X = sum(c * B for c, B in zip(rng.normal(size=len(hb)), hb))
    X = (X + X.conj().T) / 2
    w, v = np.linalg.eigh(X)
    ranks, cur = [], 1
    for i in range(1, d):
        if abs(w[i] - w[i - 1]) < 1e-7:
            cur += 1
        else:
            ranks.append(cur)
            cur = 1
    ranks.append(cur)
    return ranks


def block_L(sizes, rng):
    """Block-diagonal jump operator with the given block sizes, generic within each block."""
    d = sum(sizes)
    L = np.zeros((d, d), dtype=complex)
    o = 0
    for s in sizes:
        B = rng.normal(size=(s, s)) + 1j * rng.normal(size=(s, s))
        # shift the spectrum so different blocks carry inequivalent irreps
        B = B + (o + 1) * 3.0 * np.eye(s)
        L[o:o + s, o:o + s] = B
        o += s
    return L


def subset_sums(sizes):
    out = set()
    for k in range(len(sizes) + 1):
        for c in combinations(range(len(sizes)), k):
            out.add(sum(sizes[i] for i in c))
    return out


