"""
LANE O-1, GAP (b): FLIPPABILITY -- clause (iv), "some admissible U has U^dag R U = -R".

THE LANE BRIEF CONJECTURED: "on a degenerate subspace of dimension m >= 2, a Hermitian
involution R with both eigenvalues present always admits a unitary conjugating R to -R
within that subspace (any permutation swapping the two eigenspaces).  So flippability may
be FREE, and the whole content of clause (iv) may sit in the word ADMISSIBLE."

THAT IS FALSE AS STATED, and this file says exactly where.  A permutation swaps the two
eigenspaces of R only if they have the SAME DIMENSION.  The correct statement is:

  THEOREM O1-B (flippability is exactly a trace condition).
    Let R = R^dag, R^2 = I on a finite-dimensional Hilbert space of dimension d, with
    eigenvalue multiplicities (p, q), p + q = d.  Then
        there exists a unitary U with U^dag R U = -R   <=>   p = q   <=>   Tr R = 0.
    Proof.  (=>) unitary conjugation preserves the spectrum with multiplicity, and the
    spectrum of -R is that of R with p and q exchanged; also Tr(U^dag R U) = Tr R = -Tr R
    forces Tr R = 0.  (<=) if p = q pick orthonormal bases {u_i} of the (+1)-eigenspace
    and {v_i} of the (-1)-eigenspace and let U be the swap u_i <-> v_i.  Then
    U^dag R U = -R.  QED

  COROLLARY O1-B1 (a parity obstruction).  If dim Hilbert space is ODD, then Tr R is odd
    for every Hermitian involution R, so Tr R != 0 and NO record is writable.  Ever.
    Clause (iv) fails for parity reasons alone, no matter what "admissible" means.

  COROLLARY O1-B2 (energy-conserving writers).  If the writer is required to commute with
    H -- i.e. writing must not change the energy -- then U preserves every eigenspace and
    the condition sharpens to  tr(R|_{E_lam}) = 0 for EVERY eigenvalue lam of H.
    A record can be globally balanced and still not writable without an energy transition.

  THEOREM O1-B3 (the collision with O-4).  Let A = alg{I, H, L_k, L_k^dag}.  Clause (ii)
    puts R in A'.  If "admissible" is read as O-4's first branch -- "generated by the
    theory's own operators" -- then U is in A, so U^dag R U = R.U^dag U = R, and clause
    (iv) is UNSATISFIABLE for every R that satisfies clause (ii).  Under that reading the
    definition is inconsistent and no record exists in any system whatsoever.
    THIS IS EXACTLY P-2 SHARPENED FROM "the writer is built from neither H nor {L_k}" TO
    "the writer is outside the algebra they generate, so O-4 must take its SECOND branch."

  SO O-1 AND O-4 ARE ENTANGLED -- but not in the direction conjectured.  Flippability is
  not free-and-therefore-vacuous; it carries a genuine trace/parity obstruction that
  survives the MOST PERMISSIVE reading of "admissible", and it becomes IMPOSSIBLE under
  one of the two readings O-4 proposes.
"""

